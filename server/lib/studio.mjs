// Studio plumbing: the owner's secrets in server/.env, the studio key check, and the small settings file ($PRYSM CA).
// STUDIO_KEY gates every /api/studio/* route (x-studio-key header). PRYSM_SECRET encrypts the burn wallet's key at rest.
// Both are generated into server/.env on the first start when missing; they are never logged or sent anywhere.
import fs from "node:fs";
import path from "node:path";
import { randomBytes, timingSafeEqual } from "node:crypto";

/** Loads server/.env into process.env (values already in the env win), then fills in missing secrets. */
export function loadStudioEnv(serverDir) {
  const file = path.join(serverDir, ".env");
  let text = ""; try { text = fs.readFileSync(file, "utf8"); } catch {}
  for (const line of text.split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/); if (!m) continue;
    const v = m[2].replace(/^(['"])(.*)\1$/, "$2");
    if (process.env[m[1]] === undefined || process.env[m[1]] === "") process.env[m[1]] = v;
  }
  const add = [];
  if ((process.env.STUDIO_KEY || "").length < 16) { process.env.STUDIO_KEY = randomBytes(24).toString("base64url"); add.push(`STUDIO_KEY=${process.env.STUDIO_KEY}`); }
  if ((process.env.PRYSM_SECRET || "").length < 32) { process.env.PRYSM_SECRET = randomBytes(32).toString("base64url"); add.push(`PRYSM_SECRET=${process.env.PRYSM_SECRET}`); }
  if (add.length) {
    const sep = text && !text.endsWith("\n") ? "\n" : "";
    fs.writeFileSync(file, text + sep + "# generated by the PRYSM server on first start; keep this file private\n" + add.join("\n") + "\n", { mode: 0o600 });
    try { fs.chmodSync(file, 0o600); } catch {}
    return { generated: add.map((l) => l.slice(0, l.indexOf("="))), file };
  }
  return { generated: [], file };
}

/** constant-time compare; a key shorter than 16 characters never matches */
export function keyMatches(given, want) {
  const a = Buffer.from(String(given || "")), b = Buffer.from(String(want || ""));
  return b.length >= 16 && a.length === b.length && timingSafeEqual(a, b);
}

/** a tiny JSON store under server/data (atomic writes) */
export function createSettings(dir, defaults) {
  const file = path.join(dir, "studio.json");
  let data = { ...defaults };
  try { data = { ...defaults, ...JSON.parse(fs.readFileSync(file, "utf8")) }; } catch {}
  return {
    get data() { return data; },
    save() { fs.mkdirSync(dir, { recursive: true }); fs.writeFileSync(file + ".tmp", JSON.stringify(data, null, 1)); fs.renameSync(file + ".tmp", file); },
  };
}
